import React, { useState } from 'react';
import {
  Calendar as CalendarIcon,
  Download,
  Scissors,
  Sprout,
  ShieldAlert,
  Layers,
  Check,
  RefreshCw,
} from 'lucide-react';
import { GardenTask, TaskType } from '../shared/types';
import { api } from '../shared/api';

interface CalendarPageProps {
  tasks: GardenTask[];
  onToggleTask: (taskId: string) => void;
  onRegenerate: () => void;
  zone: string;
}

export const CalendarPage: React.FC<CalendarPageProps> = ({
  tasks,
  onToggleTask,
  onRegenerate,
  zone,
}) => {
  const [viewMode, setViewMode] = useState<'list' | 'month'>('list');
  const [selectedType, setSelectedType] = useState<string>('all');
  const [selectedMonth, setSelectedMonth] = useState<number>(new Date().getMonth());
  const [searchQuery, setSearchQuery] = useState('');

  const months = [
    'January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December',
  ];

  const filteredTasks = tasks.filter((t) => {
    if (selectedType !== 'all' && t.type !== selectedType) return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      return (
        t.title.toLowerCase().includes(q) ||
        t.plant_name.toLowerCase().includes(q) ||
        t.why.toLowerCase().includes(q)
      );
    }
    return true;
  });

  const getTaskIcon = (type: TaskType) => {
    switch (type) {
      case 'prune':
        return <Scissors className="w-3.5 h-3.5 text-stone-700" />;
      case 'fertilize':
        return <Sprout className="w-3.5 h-3.5 text-emerald-700" />;
      case 'frost_protect':
        return <ShieldAlert className="w-3.5 h-3.5 text-amber-700" />;
      case 'mulch':
        return <Layers className="w-3.5 h-3.5 text-amber-900" />;
      default:
        return <CalendarIcon className="w-3.5 h-3.5 text-stone-600" />;
    }
  };

  const tasksByMonth: Record<number, GardenTask[]> = {};
  for (let i = 0; i < 12; i++) tasksByMonth[i] = [];

  tasks.forEach((task) => {
    const parts = task.due_date.split('-');
    if (parts.length >= 2) {
      const m = parseInt(parts[1], 10) - 1;
      if (tasksByMonth[m]) {
        tasksByMonth[m].push(task);
      }
    }
  });

  const completedCount = tasks.filter((t) => t.done).length;

  return (
    <div className="space-y-8 pb-12">
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2">
            <h1 className="text-2xl font-bold font-display text-stone-900 tracking-tight">
              Deterministic Care Calendar
            </h1>
            <span className="text-xs font-mono font-medium text-stone-500">
              Zone {zone}
            </span>
          </div>
          <p className="text-xs sm:text-sm text-stone-500 mt-1">
            Generated by the Care Calendar Agent (Python). Task load is leveled to prevent weekend bottlenecks.
          </p>
        </div>

        <div className="flex items-center gap-2.5 flex-wrap">
          <button
            onClick={onRegenerate}
            className="px-3 py-2 text-xs font-medium text-stone-700 bg-white hover:bg-stone-50 border border-stone-200 rounded-xl transition-colors flex items-center gap-1.5 shadow-2xs"
            title="Re-run scheduling algorithm against current plants"
          >
            <RefreshCw className="w-3.5 h-3.5 text-stone-500" />
            Recalculate
          </button>

          <a
            href={api.getIcsExportUrl()}
            download="yard_sloth_garden_calendar.ics"
            className="px-4 py-2 text-xs font-semibold text-white bg-stone-900 hover:bg-stone-800 rounded-xl transition-all flex items-center gap-2 shadow-xs active:scale-[0.98]"
          >
            <Download className="w-3.5 h-3.5" />
            Export .ICS File
          </a>
        </div>
      </div>

      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 bg-white p-3 rounded-2xl border border-stone-200/80 shadow-2xs">
        <div className="flex items-center gap-1 p-1 bg-stone-100 rounded-xl shrink-0">
          <button
            onClick={() => setViewMode('list')}
            className={`px-3 py-1.5 text-xs font-medium rounded-lg transition-colors ${
              viewMode === 'list'
                ? 'bg-white text-stone-900 shadow-2xs'
                : 'text-stone-600 hover:text-stone-900'
            }`}
          >
            List View
          </button>
          <button
            onClick={() => setViewMode('month')}
            className={`px-3 py-1.5 text-xs font-medium rounded-lg transition-colors ${
              viewMode === 'month'
                ? 'bg-white text-stone-900 shadow-2xs'
                : 'text-stone-600 hover:text-stone-900'
            }`}
          >
            Month Grid
          </button>
        </div>

        <div className="flex items-center gap-1 overflow-x-auto">
          {[
            { id: 'all', label: 'All Chores' },
            { id: 'prune', label: 'Pruning' },
            { id: 'fertilize', label: 'Feeding' },
            { id: 'frost_protect', label: 'Frost Watch' },
            { id: 'mulch', label: 'Winterizing' },
          ].map((f) => (
            <button
              key={f.id}
              onClick={() => setSelectedType(f.id)}
              className={`px-3 py-1.5 text-xs font-medium rounded-lg whitespace-nowrap transition-colors ${
                selectedType === f.id
                  ? 'bg-stone-900 text-stone-100 font-semibold'
                  : 'text-stone-600 hover:bg-stone-100'
              }`}
            >
              {f.label}
            </button>
          ))}
        </div>

        <div className="text-right text-xs font-mono text-stone-500 tabular-nums shrink-0 px-2">
          <span className="font-bold text-stone-900">{completedCount}</span> / {tasks.length} Completed
        </div>
      </div>

      {viewMode === 'month' && (
        <div className="space-y-6">
          <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-4 gap-3.5">
            {months.map((monthName, idx) => {
              const monthTasks = tasksByMonth[idx] || [];
              const isSelected = selectedMonth === idx;
              const hasTasks = monthTasks.length > 0;

              return (
                <button
                  key={monthName}
                  onClick={() => setSelectedMonth(idx)}
                  className={`text-left p-4 rounded-2xl border transition-all ${
                    isSelected
                      ? 'bg-stone-900 text-white border-stone-900 shadow-sm'
                      : 'bg-white hover:border-stone-300 border-stone-200/80 text-stone-900 shadow-2xs'
                  }`}
                >
                  <div className="flex items-center justify-between">
                    <span className="font-bold font-display text-sm">
                      {monthName}
                    </span>
                    <span
                      className={`font-mono text-xs font-semibold tabular-nums px-2 py-0.5 rounded ${
                        isSelected
                          ? 'bg-stone-800 text-stone-200'
                          : hasTasks
                          ? 'bg-emerald-50 text-emerald-800'
                          : 'bg-stone-100 text-stone-400'
                      }`}
                    >
                      {monthTasks.length} {monthTasks.length === 1 ? 'task' : 'tasks'}
                    </span>
                  </div>

                  <div className="mt-3 text-xs opacity-75 space-y-1">
                    {monthTasks.slice(0, 2).map((t) => (
                      <div key={t.id} className="truncate text-[11px]">
                        • {t.title}
                      </div>
                    ))}
                    {monthTasks.length > 2 && (
                      <div className="text-[10px] font-mono opacity-80">
                        +{monthTasks.length - 2} more...
                      </div>
                    )}
                  </div>
                </button>
              );
            })}
          </div>

          <div className="bg-white rounded-2xl p-6 border border-stone-200/80 shadow-2xs space-y-4">
            <h3 className="text-lg font-bold font-display text-stone-900">
              Tasks Scheduled for {months[selectedMonth]}
            </h3>

            {tasksByMonth[selectedMonth].length === 0 ? (
              <p className="text-xs text-stone-500 py-4">
                No garden chores scheduled for this month. The yard rests.
              </p>
            ) : (
              <div className="space-y-3">
                {tasksByMonth[selectedMonth].map((task) => (
                  <div
                    key={task.id}
                    className={`p-4 rounded-xl border flex items-start justify-between gap-4 transition-all ${
                      task.done
                        ? 'bg-stone-50 border-stone-200/60 opacity-60'
                        : 'bg-white border-stone-200 hover:border-stone-300'
                    }`}
                  >
                    <div className="flex items-start gap-3">
                      <button
                        onClick={() => onToggleTask(task.id)}
                        className={`w-5 h-5 rounded-md flex items-center justify-center shrink-0 mt-0.5 transition-colors ${
                          task.done
                            ? 'bg-emerald-700 text-white'
                            : 'border border-stone-300 hover:border-stone-400 bg-stone-50'
                        }`}
                      >
                        {task.done && <Check className="w-3.5 h-3.5 stroke-[3]" />}
                      </button>

                      <div>
                        <div
                          className={`text-sm font-semibold ${
                            task.done ? 'line-through text-stone-500' : 'text-stone-900'
                          }`}
                        >
                          {task.title}
                        </div>
                        <div className="text-xs text-stone-500 font-medium mt-0.5">
                          {task.plant_name} · Due {task.due_date}
                        </div>
                        <div className="text-xs text-stone-600 mt-2 leading-relaxed">
                          <span className="font-semibold text-stone-900">Why: </span>
                          {task.why}
                        </div>
                        <div className="text-xs text-stone-600 mt-1 leading-relaxed">
                          <span className="font-semibold text-stone-900">How: </span>
                          {task.how}
                        </div>
                      </div>
                    </div>
                  </div>
                ))}
              </div>
            )}
          </div>
        </div>
      )}

      {viewMode === 'list' && (
        <div className="space-y-4">
          {filteredTasks.length === 0 ? (
            <div className="bg-white p-8 rounded-2xl border border-stone-200 text-center">
              <p className="text-xs text-stone-500">
                No tasks match the selected filter.
              </p>
            </div>
          ) : (
            filteredTasks.map((task) => (
              <div
                key={task.id}
                className={`bg-white rounded-2xl border p-5 sm:p-6 transition-all ${
                  task.done
                    ? 'border-stone-200/60 bg-stone-50/50 opacity-65'
                    : 'border-stone-200/80 hover:border-stone-300 shadow-2xs'
                }`}
              >
                <div className="flex items-start justify-between gap-4">
                  <div className="flex items-start gap-3.5">
                    <button
                      onClick={() => onToggleTask(task.id)}
                      className={`w-5 h-5 rounded-md flex items-center justify-center shrink-0 mt-0.5 transition-colors ${
                        task.done
                          ? 'bg-emerald-700 text-white'
                          : 'border border-stone-300 hover:border-stone-400 bg-stone-50'
                      }`}
                      title={task.done ? 'Mark pending' : 'Mark completed'}
                    >
                      {task.done && <Check className="w-3.5 h-3.5 stroke-[3]" />}
                    </button>

                    <div>
                      <div className="flex items-center gap-2 flex-wrap">
                        <h3
                          className={`text-base font-bold font-display ${
                            task.done ? 'line-through text-stone-500' : 'text-stone-900'
                          }`}
                        >
                          {task.title}
                        </h3>
                        <span className="text-xs text-stone-400">·</span>
                        <span className="text-xs font-semibold text-stone-700">
                          {task.plant_name}
                        </span>
                      </div>

                      <div className="mt-3 space-y-2 text-xs sm:text-sm">
                        <div className="p-3 rounded-xl bg-stone-50 border border-stone-100 text-stone-700 leading-relaxed">
                          <span className="font-semibold text-stone-900 font-sans">Why: </span>
                          {task.why}
                        </div>
                        <div className="p-3 rounded-xl bg-stone-50 border border-stone-100 text-stone-700 leading-relaxed">
                          <span className="font-semibold text-stone-900 font-sans">How: </span>
                          {task.how}
                        </div>
                      </div>
                    </div>
                  </div>

                  <div className="text-right shrink-0">
                    <div className="font-mono text-xs font-semibold tabular-nums text-stone-900">
                      {task.due_date}
                    </div>
                    <div className="flex items-center justify-end gap-1 text-[11px] text-stone-500 uppercase tracking-wider font-mono mt-1">
                      {getTaskIcon(task.type)}
                      <span>{task.type.replace('_', ' ')}</span>
                    </div>
                  </div>
                </div>
              </div>
            ))
          )}
        </div>
      )}
    </div>
  );
};
