"""
agents/llm/ollama_client.py

Structured plant-care profiles via local Ollama (no hardcoded fallbacks).
"""

import json
import os
import re
import urllib.error
import urllib.request
from typing import Any, Dict, Optional

DEFAULT_MODEL = "gemma4:31b-cloud"
DEFAULT_HOST = "http://localhost:11434"

BLOOM_WOOD = frozenset({"old_wood", "new_wood", "both", "not_applicable"})
FROST_SENSITIVITY = frozenset({"tender", "semi_hardy", "hardy"})
CARE_CATEGORY = frozenset(
    {"shrub", "perennial", "annual", "fruit_tree", "vegetable", "herb", "houseplant"}
)


class OllamaError(RuntimeError):
    """Raised when Ollama is unreachable or returns unusable output."""


def _ollama_config() -> tuple[str, str]:
    try:
        from agents.memory.agent_memory import memory

        settings = memory.get_settings()
        host = (settings.get("ollama_endpoint") or os.environ.get("OLLAMA_HOST") or DEFAULT_HOST).rstrip(
            "/"
        )
        model = settings.get("ollama_model") or os.environ.get("OLLAMA_MODEL") or DEFAULT_MODEL
    except Exception:
        host = (os.environ.get("OLLAMA_HOST") or DEFAULT_HOST).rstrip("/")
        model = os.environ.get("OLLAMA_MODEL") or DEFAULT_MODEL
    return host, model


def _extract_json_object(text: str) -> Dict[str, Any]:
    raw = text.strip()
    if not raw:
        raise OllamaError("Ollama returned an empty response.")

    fence = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", raw, re.DOTALL | re.IGNORECASE)
    if fence:
        raw = fence.group(1)

    start = raw.find("{")
    end = raw.rfind("}")
    if start == -1 or end == -1 or end <= start:
        raise OllamaError("Ollama response did not contain a JSON object.")

    try:
        return json.loads(raw[start : end + 1])
    except json.JSONDecodeError as exc:
        raise OllamaError(f"Could not parse Ollama JSON: {exc}") from exc


def _validate_plant_profile(data: Dict[str, Any], plant_name: str) -> Dict[str, Any]:
    required_strings = [
        "common_name",
        "species",
        "bloom_wood",
        "prune_window",
        "prune_rules",
        "fertilize_window",
        "fertilize_type",
        "mulch_rules",
        "frost_sensitivity",
        "care_category",
    ]
    missing = [k for k in required_strings if not str(data.get(k, "")).strip()]
    if missing:
        raise OllamaError(f"Ollama JSON missing fields: {', '.join(missing)}")

    bloom_wood = str(data["bloom_wood"]).strip().lower()
    frost_sensitivity = str(data["frost_sensitivity"]).strip().lower()
    care_category = str(data["care_category"]).strip().lower()

    if bloom_wood not in BLOOM_WOOD:
        raise OllamaError(f"Invalid bloom_wood '{bloom_wood}' from Ollama.")
    if frost_sensitivity not in FROST_SENSITIVITY:
        raise OllamaError(f"Invalid frost_sensitivity '{frost_sensitivity}' from Ollama.")
    if care_category not in CARE_CATEGORY:
        raise OllamaError(f"Invalid care_category '{care_category}' from Ollama.")

    try:
        frost_threshold_f = int(round(float(data.get("frost_threshold_f"))))
    except (TypeError, ValueError):
        raise OllamaError("Ollama JSON must include numeric frost_threshold_f.")

    host, model = _ollama_config()
    return {
        "common_name": str(data["common_name"]).strip(),
        "species": str(data["species"]).strip(),
        "bloom_wood": bloom_wood,
        "prune_window": str(data["prune_window"]).strip(),
        "prune_rules": str(data["prune_rules"]).strip(),
        "fertilize_window": str(data["fertilize_window"]).strip(),
        "fertilize_type": str(data["fertilize_type"]).strip(),
        "mulch_rules": str(data["mulch_rules"]).strip(),
        "frost_sensitivity": frost_sensitivity,
        "frost_threshold_f": frost_threshold_f,
        "care_category": care_category,
        "source": f"ollama:{model}@{host}",
        "reasoning_summary": str(data.get("reasoning_summary", "")).strip()
        or f"Profile generated by Ollama for “{plant_name}”.",
    }


def _chat(prompt: str, system: str) -> str:
    host, model = _ollama_config()
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": prompt},
        ],
        "stream": False,
        "format": "json",
        "options": {"temperature": 0.2},
    }
    url = f"{host}/api/chat"
    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=120) as response:
            body = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise OllamaError(
            f"Ollama HTTP {exc.code} at {host}. Is Ollama running with model “{model}”? {detail[:200]}"
        ) from exc
    except urllib.error.URLError as exc:
        raise OllamaError(
            f"Cannot reach Ollama at {host}. Start Ollama and pull model “{model}”."
        ) from exc

    message = body.get("message") or {}
    content = message.get("content")
    if not content:
        raise OllamaError(f"Ollama returned no message content (model={model}).")
    return str(content)


def check_ollama_status() -> Dict[str, Any]:
    """Ping Ollama and report whether the configured model is available."""
    host, model = _ollama_config()
    url = f"{host}/api/tags"
    req = urllib.request.Request(url, headers={"Content-Type": "application/json"}, method="GET")
    try:
        with urllib.request.urlopen(req, timeout=8) as response:
            body = json.loads(response.read().decode("utf-8"))
    except urllib.error.URLError as exc:
        return {
            "ok": False,
            "host": host,
            "model": model,
            "error": f"Cannot reach Ollama: {exc}",
        }

    names = [m.get("name", "") for m in body.get("models", [])]
    model_ready = any(model in n or n.startswith(f"{model}:") for n in names)
    return {
        "ok": model_ready,
        "host": host,
        "model": model,
        "models_available": names,
        "error": None if model_ready else f"Model “{model}” not found in Ollama. Run: ollama pull {model}",
    }


def fetch_plant_care_profile(plant_name: str, species: Optional[str] = None) -> Dict[str, Any]:
    """
    Ask Ollama for a horticulturally grounded plant profile. No static fallback.
    Results are cached on disk so repeat lookups skip the LLM.
    """
    name = (plant_name or "").strip()
    if not name:
        raise OllamaError("Plant name is required for Ollama lookup.")

    sci = (species or "").strip()

    try:
        from agents.memory.agent_memory import memory

        cached = memory.get_cached_plant_profile(name, sci or None)
        if cached:
            cached = {**cached, "source": f"{cached.get('source', 'cache')} (cached)"}
            return cached
    except Exception:
        pass

    _, model = _ollama_config()

    system = (
        "You are a master gardener and botanist. Respond with a single JSON object only. "
        "Use accurate horticulture for temperate US home gardens. "
        "Never invent a random plant: if the name is ambiguous, pick the most common garden "
        "species and set species accordingly."
    )
    user_prompt = f"""Plant lookup request:
- User label: "{name}"
- Scientific name hint (may be empty): "{sci}"

Return JSON with exactly these keys:
{{
  "common_name": string,
  "species": string (binomial or cultivar group),
  "bloom_wood": one of old_wood | new_wood | both | not_applicable,
  "prune_window": string,
  "prune_rules": string (actionable steps),
  "fertilize_window": string,
  "fertilize_type": string,
  "mulch_rules": string,
  "frost_sensitivity": one of tender | semi_hardy | hardy,
  "frost_threshold_f": integer (night temperature °F when protection is needed),
  "care_category": one of shrub | perennial | annual | fruit_tree | vegetable | herb | houseplant,
  "reasoning_summary": string (2-3 sentences: why bloom_wood and frost threshold apply)
}}"""

    content = _chat(user_prompt, system)
    parsed = _extract_json_object(content)
    profile = _validate_plant_profile(parsed, name)

    try:
        from agents.memory.agent_memory import memory

        memory.set_cached_plant_profile(name, sci or None, profile)
    except Exception as exc:
        print("Plant profile cache save failed:", exc)

    return profile
